  static Optional<Topic> find(String id) {
    return ALL.stream().filter(t -> t.id().equals(id)).findFirst();
  }

  static List<LaboratoryCommandPalette.Command> commands() {
    return ALL.stream()
        .map(
            t ->
                new LaboratoryCommandPalette.Command(
                    t.id(),
                    t.name(),
                    "Углублённое · редактор и файлы",
                    t.guide().texts()[0],
                    () -> {}))
        .toList();
  }
