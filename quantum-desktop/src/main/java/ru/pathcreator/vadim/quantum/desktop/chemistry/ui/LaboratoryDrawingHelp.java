package ru.pathcreator.vadim.quantum.desktop.chemistry.ui;

import javafx.scene.control.ButtonType;
import javafx.scene.control.Dialog;
import javafx.scene.control.Label;
import javafx.scene.control.ScrollPane;
import javafx.scene.layout.VBox;
import javafx.stage.Window;

final class LaboratoryDrawingHelp {
  private LaboratoryDrawingHelp() {}

  static void show(final Window owner) {
    final Dialog<Void> dialog = new Dialog<>();
    dialog.initOwner(owner);
    dialog.setTitle("Построение и управление");
    dialog.setResizable(true);
    LaboratoryDialogStyle.apply(dialog, owner);
    final VBox content = new VBox(12);
    content.setPadding(new javafx.geometry.Insets(14));
    section(
        content,
        "Структура с нуля",
        "Выберите кольцо слева и нажмите на свободное место. Нажатие на атом присоединит кольцо; на связь — добавит конденсированное кольцо. Выбор элемента справа только включает инструмент: нажатие на атом заменяет его, на пустой лист — создаёт отдельный атом. Он не соединяется с прежним выделенным атомом автоматически. Тяните от атома в режиме «Атом», чтобы продолжить структуру связью.");
    section(
        content,
        "Связи и заместители",
        "1 / 2 / 3 включают инструменты одинарной, двойной или тройной связи. Протяните от атома в свободное место, чтобы добавить заместитель, либо к другому атому, чтобы соединить их. В режиме «Атом» или обычном режиме «Связь» нажатие переключает обычную связь 1 → 2 → 3 → 1. Явные инструменты 2 и 3 задают выбранную кратность. Ароматическая связь не участвует в этом цикле; стереосвязь автоматически не преобразуется.");
    section(
        content,
        "Выделение и правки",
        "V — выбор и перемещение. C / N / O / S / F / P / H / I выбирают элемент, L — Cl (хлор), B — Br (бром); выбор клавишей, как и в палитре, сам по себе не меняет атом. Рамка выделяет несколько атомов; Shift добавляет к выделению. Инструмент «Фрагмент» выбирает связную часть. Правая кнопка на атоме или связи открывает свойства и команды. Ctrl+C / Ctrl+V — копирование и вставка в центр видимой области. Несколько фрагментов вставляются вместе и отменяются одним действием; Delete — удалить выделенное.");
    section(
        content,
        "Поворот и отражение",
        "Кнопки над листом поворачивают выбранный компонент на 90° или отражают его. Для поворота мышью выберите круговую стрелку слева и тяните атом или связь вокруг центра молекулы. Шаг — 15°; Alt даёт свободный угол. Esc отменяет незавершённый жест; Ctrl+Z отменяет весь поворот. Отражение сохраняет абсолютную стереохимию, меняя направление клиньев.");
    section(
        content,
        "Название IUPAC",
        "Выберите атом нужной молекулы и нажмите «Название IUPAC». Поиск в PubChem использует только выбранную структуру, требует интернета и проверяет совпадение графа. На карточке можно применить найденное название; своё имя вещества сохраняется, пока вы явно не замените его. Если записи нет, название не выдумывается.");
    section(
        content,
        "Компактная формула",
        "В новых скелетных рисунках H дополняются автоматически для поддерживаемых нейтральных валентностей и учитываются в формуле и молярной массе. «Все H» над листом или «Вид → Показать все водороды» раскрывает их связями; эта кнопка меняет только вид. В компактном виде C–H скрыты, а H при гетероатомах показаны группами. Для старых рисунков нажмите «Учесть водороды» в подсказке над листом; это отдельное действие с отменой. Для зарядов, радикалов и неоднозначных связей проверьте H через «Вид → Водороды вручную…». Изотопные H и стереосвязи сохраняются.");
    section(
        content,
        "Вид и навигация",
        "«Вписать» показывает весь рисунок; «Разместить» переставляет компоненты и отменяется через Ctrl+Z. Инструмент «Рука», пробел с перетаскиванием или средняя кнопка мыши сдвигают лист без изменения структуры. Ctrl + колесо и жест масштабирования тачпада меняют масштаб около курсора; кнопки −/+ — около центра. «Вид → Названия молекул» включает подписи молекул. Цифра снизу в NH₂ — число водородов, сверху слева у атома — массовое число изотопа; это химические обозначения, а не нумерация. Настройки вида сохраняются на этом компьютере отдельно от опыта.");
    section(
        content,
        "Геометрия",
        "В «3D» выберите компонент из списка; «2D + 3D» показывает оба вида рядом. «Вращение» и «Перемещение» выбирают действие мыши; Shift + перетаскивание или средняя кнопка временно включают перемещение. Колесо меняет масштаб около курсора, двойной щелчок сбрасывает вид. Кнопки ↶/↷ поворачивают камеру на 90°, «Ракурс» задаёт вид спереди, сверху или сбоку. После нажатия на 3D-поле стрелки вращают камеру с шагом 15°, Shift + стрелки сдвигают её. Камера не меняет координаты молекулы. При отсутствии геометрии используйте «Построить 3D»; это начальная раскладка, а не оптимизация.");
    section(
        content,
        "Сохранение и отмена",
        "Ctrl+S — сохранить опыт; Ctrl+O — открыть; Ctrl+N — новый опыт. Ctrl+Z — отмена; Ctrl+Y или Ctrl+Shift+Z — повтор. На macOS используйте Command вместо Ctrl для сочетаний клавиш. План и фактические количества доступны в панели «Компоненты».");
    final ScrollPane scroll = new ScrollPane(content);
    scroll.setFitToWidth(true);
    scroll.setPrefViewportWidth(570);
    scroll.setPrefViewportHeight(540);
    dialog.getDialogPane().setContent(scroll);
    dialog
        .getDialogPane()
        .getButtonTypes()
        .add(new ButtonType("Закрыть", javafx.scene.control.ButtonBar.ButtonData.CANCEL_CLOSE));
    dialog.showAndWait();
  }

  private static void section(final VBox content, final String title, final String text) {
    final Label heading = new Label(title);
    heading.getStyleClass().add("laboratory-drawing-guide-title");
    final Label body = new Label(text);
    body.setWrapText(true);
    body.setMinHeight(javafx.scene.layout.Region.USE_PREF_SIZE);
    content.getChildren().add(new VBox(4, heading, body));
  }
}
